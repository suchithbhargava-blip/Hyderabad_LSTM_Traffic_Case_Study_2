plt.grid(True); plt.show()

"""## 5. Define LSTM features and chronological sequences
Each location is treated as a separate time series. The previous 24 observations (6 hours) predict the next 15-minute speed and congestion index. The train/test split is chronological to avoid training on future observations.
"""

FEATURES = [
    "current_speed_kmph", "free_flow_speed_kmph", "congestion_index",
    "rainfall_mm", "temperature_c", "is_weekend",
    "hour_sin", "hour_cos", "day_sin", "day_cos"
]
TARGETS = ["current_speed_kmph", "congestion_index"]
TIME_STEPS = 24
INTERVAL_MINUTES = 15

train_groups, test_groups = [], []
for loc, g in df.groupby("location"):
    g = g.sort_values("timestamp").reset_index(drop=True)
    cut = int(len(g)*0.80)
    train_groups.append(g.iloc[:cut].copy())
    test_groups.append(g.iloc[cut:].copy())

train_df = pd.concat(train_groups, ignore_index=True)
test_df = pd.concat(test_groups, ignore_index=True)

x_scaler = MinMaxScaler()
y_scaler = MinMaxScaler()
x_scaler.fit(train_df[FEATURES])
y_scaler.fit(train_df[TARGETS])

def make_sequences(frame):
    X, y, meta = [], [], []
    for loc, g in frame.groupby("location"):
        g = g.sort_values("timestamp").reset_index(drop=True)
        xs = x_scaler.transform(g[FEATURES])
        ys = y_scaler.transform(g[TARGETS])
        for i in range(TIME_STEPS, len(g)):
            times = g["timestamp"].iloc[i-TIME_STEPS:i+1]
            if not (times.diff().dropna() == pd.Timedelta(minutes=INTERVAL_MINUTES)).all():
                continue
            X.append(xs[i-TIME_STEPS:i])
            y.append(ys[i])
            meta.append({"location":loc, "timestamp":g.loc[i,"timestamp"]})
    return np.array(X, dtype=np.float32), np.array(y, dtype=np.float32), pd.DataFrame(meta)

X_train, y_train, meta_train = make_sequences(train_df)
X_test, y_test, meta_test = make_sequences(test_df)

print("X_train:", X_train.shape, "y_train:", y_train.shape)
print("X_test :", X_test.shape, "y_test :", y_test.shape)

"""## 6. Build and train multivariate LSTM"""

model = Sequential([
    Input(shape=(TIME_STEPS, len(FEATURES))),
    LSTM(64, return_sequences=True),
    Dropout(0.2),
    LSTM(32),
    Dropout(0.2),
    Dense(16, activation="relu"),
    Dense(2)
])
model.compile(optimizer="adam", loss="mse", metrics=["mae"])
model.summary()

early_stop = EarlyStopping(monitor="val_loss", patience=6, restore_best_weights=True)
history = model.fit(
    X_train, y_train,
    validation_split=0.15,
    epochs=30,
    batch_size=64,
    shuffle=False,
    callbacks=[early_stop],
    verbose=1
)
print("Training completed.")

"""## 7. Plot training history"""

plt.figure(figsize=(9,4))
plt.plot(history.history["loss"], label="Training loss")
plt.plot(history.history["val_loss"], label="Validation loss")
plt.title("LSTM Training and Validation Loss")
plt.xlabel("Epoch"); plt.ylabel("MSE loss")
plt.legend(); plt.grid(True); plt.show()

"""## 8. Evaluate model using MAE, RMSE and R²"""

pred_scaled = model.predict(X_test, verbose=0)
actual = y_scaler.inverse_transform(y_test)
predicted = y_scaler.inverse_transform(pred_scaled)

metric_rows = []
for j, target in enumerate(TARGETS):
    metric_rows.append({
        "Target": target,
        "MAE": mean_absolute_error(actual[:,j], predicted[:,j]),
        "RMSE": np.sqrt(mean_squared_error(actual[:,j], predicted[:,j])),
        "R2": r2_score(actual[:,j], predicted[:,j])
    })
metrics = pd.DataFrame(metric_rows)
display(metrics.round(4))
print("Lower MAE/RMSE is better. R² closer to 1 is better.")

"""## 9. Actual vs predicted plots"""

for j, target in enumerate(TARGETS):
    n = min(400, len(actual))
    plt.figure(figsize=(13,4))
    plt.plot(actual[:n,j], label="Actual")
    plt.plot(predicted[:n,j], label="Predicted")
    plt.title(f"Actual vs Predicted: {target}")
    plt.xlabel("Test observations"); plt.ylabel(target)
    plt.legend(); plt.grid(True); plt.show()

"""## 10. Save prediction table and evaluation metrics"""

results = meta_test.copy()
results["actual_speed_kmph"] = actual[:,0]
results["predicted_speed_kmph"] = predicted[:,0]
results["actual_congestion_index"] = actual[:,1]
results["predicted_congestion_index"] = predicted[:,1]
results.to_csv("hyderabad_lstm_predictions.csv", index=False)
metrics.to_csv("hyderabad_lstm_metrics.csv", index=False)
display(results.head(15).round(2))
print("Saved prediction and metric CSV files.")

"""## 11. Forecast the next 15 minutes for each hotspot"""

forecast_rows = []
for loc, g in df.groupby("location"):
    g = g.sort_values("timestamp").tail(TIME_STEPS).copy()
    if len(g) != TIME_STEPS:
        continue
    if not (g["timestamp"].diff().dropna() == pd.Timedelta(minutes=15)).all():
        print("Skipping", loc, "- recent sequence has a time gap")
        continue
    x = x_scaler.transform(g[FEATURES]).reshape(1,TIME_STEPS,len(FEATURES))
    p = y_scaler.inverse_transform(model.predict(x, verbose=0))[0]
    forecast_rows.append({
        "location":loc,
        "forecast_time":g["timestamp"].iloc[-1] + pd.Timedelta(minutes=15),
        "predicted_speed_kmph":max(0,float(p[0])),
        "predicted_congestion_index":float(np.clip(p[1],0,100))
    })
forecast = pd.DataFrame(forecast_rows)
display(forecast.round(2))
forecast.to_csv("hyderabad_next_15min_forecast.csv", index=False)
print("Forecast saved.")

